def _plot_la_voronoi(ax):
    """Fig. 4a: Voronoi partition of Los Angeles with center points."""
    boundary = gpd.read_file(CLUSTERS_PATH, where=f"ID_UC_G0 = {LA_ID}").to_crs('EPSG:3857')
