"""
Voronoi-based spatial regularity analysis of urban centers (Figure 4).

Computation:
  - Generates empirical Voronoi partitions of urban centers within city boundaries.
  - Runs Monte Carlo simulations under two null models:
    * CSR (Complete Spatial Randomness): uniform random points within city polygons.
    * SSI (Sequential Spatial Inhibition): random points with minimum inter-point
      distance derived from the minimum contour area threshold (4 km2).
  - Outputs: empirical Voronoi shapefile and cached null model statistics (.npz).

Figure 4:
    (a) Voronoi partition of Los Angeles with center points.
    (b) Violin plot of Voronoi cell areas across countries (mono- vs polycentric).
    (c) Error bar plot of Voronoi cell areas for selected cities.
    (d) Schematic of null models (CSR and SSI) — not generated by this code.
    (e) KDE of CV and mean NND from CSR/SSI null models vs empirical.
"""

