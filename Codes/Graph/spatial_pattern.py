    cv_csr = data['cv_poisson']
    cv_ssi = data['cv_ssi']
    cv_emp = float(data['cv_emp'])

    nnd_csr = data['nnd_poisson'] / 1000
    nnd_ssi = data['nnd_ssi'] / 1000
    nnd_emp = float(data['nnd_emp']) / 1000

