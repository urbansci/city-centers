# ── Point generation ──────────────────────────────────────────────────────────

def _random_csr(polys, rng):
    """Generate CSR (uniform random) points within each city polygon."""
    gdf = polys.copy().to_crs(3857)
    all_points, all_ids = [], []
    for _, row in gdf.iterrows():
        poly = row.geometry
        n = int(row['Center_Num'])
        if n <= 0:
            continue
        minx, miny, maxx, maxy = poly.bounds
        pts = []
        while len(pts) < n:
            x, y = rng.uniform(minx, maxx), rng.uniform(miny, maxy)
            if poly.contains(Point(x, y)):
                pts.append(Point(x, y))
        all_points.extend(pts)
        all_ids.extend([row['ID_UC_G0']] * n)
    return gpd.GeoDataFrame({'ID_UC_G0': all_ids}, geometry=all_points, crs=gdf.crs).to_crs(4326)


def _random_ssi(polys, rng, max_attempts=10000):
    """Generate SSI points with minimum geodesic distance constraint."""
    geod = Geod(ellps='WGS84')
    transformer = Transformer.from_crs(3857, 4326, always_xy=True)
    gdf = polys.copy().to_crs(3857)
    all_points, all_ids = [], []

    for _, row in gdf.iterrows():
        poly = row.geometry
        n = int(row['Center_Num'])
        city_id = row['ID_UC_G0']
        if n <= 0:
            continue

        pts, pts_lonlat = [], []
        minx, miny, maxx, maxy = poly.bounds
        attempts = 0
        while len(pts) < n and attempts < max_attempts * n:
            x, y = rng.uniform(minx, maxx), rng.uniform(miny, maxy)
            attempts += 1
            if not poly.contains(Point(x, y)):
                continue
            lon, lat = transformer.transform(x, y)
            if pts_lonlat:
                lons_acc, lats_acc = zip(*pts_lonlat)
                _, _, dists = geod.inv(
                    [lon] * len(pts_lonlat), [lat] * len(pts_lonlat),
                    list(lons_acc), list(lats_acc))
                if min(dists) < INHIBITION_RADIUS:
                    continue
            pts.append(Point(x, y))
            pts_lonlat.append((lon, lat))

        if len(pts) < n:
            print(f"Warning: city {city_id} only placed {len(pts)}/{n} points")
        all_points.extend(pts)
        all_ids.extend([city_id] * len(pts))

    return gpd.GeoDataFrame({'ID_UC_G0': all_ids}, geometry=all_points, crs=gdf.crs).to_crs(4326)


# ── Voronoi computation ───────────────────────────────────────────────────────

def _points_to_voronoi(coords, clip_poly):
    """Compute Voronoi polygons for points within a clipping polygon."""
    n = len(coords)
    if n == 1:
        return [clip_poly]

    if n == 2:
        mid = coords.mean(axis=0)
        vec = coords[1] - coords[0]
        perp = np.array([-vec[1], vec[0]])
        line = LineString([mid - perp * 1e5, mid + perp * 1e5])
        split_polys = [p for p in split(clip_poly, line).geoms if not p.is_empty]
        left, right = [], []
        for p in split_polys:
            c = np.array([p.centroid.x, p.centroid.y])
            cross = perp[0] * (c[1] - mid[1]) - perp[1] * (c[0] - mid[0])
            (left if cross > 0 else right).append(p)
        return [unary_union(left), unary_union(right)]

    points = [Point(c) for c in coords]
    mp = MultiPoint(points)
    try:
        vor = voronoi_polygons(mp, extend_to=clip_poly)
    except Exception:
        rng_jitter = np.random.default_rng(seed=hash(coords.tobytes()) & 0xFFFFFFFF)
        jittered = coords + rng_jitter.uniform(-0.01, 0.01, coords.shape)
        mp = MultiPoint([Point(c) for c in jittered])
        try:
            vor = voronoi_polygons(mp, extend_to=clip_poly)
        except Exception:
            try:
                vor = voronoi_polygons(mp)
            except Exception:
                return None

    clip_valid = clip_poly if clip_poly.is_valid else clip_poly.buffer(0)
    result = [None] * n
    for cell in vor.geoms:
        clipped = cell.intersection(clip_valid)
        if clipped.is_empty:
            continue
        for i, pt in enumerate(points):
            if result[i] is None and cell.contains(pt):
                result[i] = clipped
                break

    for i in range(n):
        if result[i] is not None:
            continue
        pt = points[i]
        best_dist, best_cell = float('inf'), None
        for cell in vor.geoms:
            d = cell.boundary.distance(pt)
            if d < best_dist:
                best_dist, best_cell = d, cell
        if best_cell is not None:
            result[i] = best_cell.intersection(clip_valid)

    return None if any(r is None for r in result) else result


def voronoi_partition(pts, polys):
    """Generate Voronoi partitions of centers within each city polygon."""
    pts = pts.to_crs(3857)
    polys = polys.to_crs(3857)
    results = []

    for _, poly_row in tqdm(polys.iterrows(), total=len(polys), leave=False):
        poly_geom = poly_row.geometry
        idx = poly_row['ID_UC_G0']
        pts_in = pts[pts['ID_UC_G0'] == idx]
        country = poly_row['Country']

        if len(pts_in) == 0:
            continue
        coords = np.vstack(pts_in.geometry.apply(lambda p: (p.x, p.y)).values)
        vor_polys = _points_to_voronoi(coords, poly_geom.buffer(0))

        if vor_polys is None:
            print(f"\nSkipping ID_UC_G0 {idx} due to unresolvable topology")
            continue

        results.append(gpd.GeoDataFrame({
            'ID_UC_G0': [idx] * len(vor_polys),
            'Country': [country] * len(vor_polys),
            'CenterIdx': pts_in.index.tolist(),
        }, geometry=vor_polys, crs=polys.crs))

    merged = gpd.GeoDataFrame(pd.concat(results, ignore_index=True), crs=polys.crs)
    merged.geometry = merged.geometry.apply(lambda g: g.buffer(0) if g is not None else g)

    merged_4326 = merged.to_crs(4326)
    geod = Geod(ellps='WGS84')
    merged['Area'] = merged_4326.geometry.apply(
        lambda geom: abs(geod.geometry_area_perimeter(geom)[0]) / 1e6)

    return merged


# ── Spatial metrics ───────────────────────────────────────────────────────────

def _mark_interior(voronoi_gdf, polys):
    """Mark Voronoi cells as interior (True) if they don't touch the city boundary."""
    voronoi_proj = voronoi_gdf.to_crs(3857)
    polys_proj = polys.to_crs(3857)
    boundary_map = dict(zip(polys_proj['ID_UC_G0'], polys_proj.geometry.boundary))

    is_interior = pd.Series(True, index=voronoi_proj.index)
    for idx, row in voronoi_proj.iterrows():
        boundary = boundary_map.get(row['ID_UC_G0'])
        if boundary is not None and row.geometry is not None:
            try:
                is_interior[idx] = not row.geometry.intersects(boundary)
            except Exception:
                is_interior[idx] = False
    return is_interior


def _pool_nnd(pts_gdf, voronoi_gdf, valid_ids, interior_mask):
    """Compute pooled nearest-neighbor distances for interior centers."""
    geod = Geod(ellps='WGS84')
    if pts_gdf.crs is not None and pts_gdf.crs.to_string() != "EPSG:4326":
        pts_gdf = pts_gdf.to_crs(4326)
    lons = pts_gdf.geometry.x.values
    lats = pts_gdf.geometry.y.values
    coords_rad = np.column_stack([np.radians(lats), np.radians(lons)])
    groups = pts_gdf['ID_UC_G0'].values

    vor_interior = interior_mask.values if hasattr(interior_mask, 'values') else np.array(interior_mask)
    city_interior = {}
    for g_id in valid_ids:
        city_interior[g_id] = vor_interior[voronoi_gdf['ID_UC_G0'].values == g_id]

    all_nnd = []
    for g_id in np.unique(groups):
        if g_id not in valid_ids:
            continue
        mask = groups == g_id
        n_pts = mask.sum()
        if n_pts < 2:
            continue
        is_int = city_interior.get(g_id)
        if is_int is None or len(is_int) != n_pts:
            continue
        g_coords = coords_rad[mask]
        g_lons, g_lats = lons[mask], lats[mask]
        tree = BallTree(g_coords, metric='haversine')
        _, indices = tree.query(g_coords, k=2)
        nb = indices[:, 1]
        _, _, dists = geod.inv(g_lons, g_lats, g_lons[nb], g_lats[nb])
        for j in range(n_pts):
            if is_int[j]:
                all_nnd.append(dists[j])
    return np.array(all_nnd)


# ── Null model simulation ─────────────────────────────────────────────────────

def run_null_model(pts_emp, polys, voronoi_emp, n_sim=N_SIMULATIONS):
    """Run CSR and SSI null model simulations, cache results to .npz."""
    emp_interior = _mark_interior(voronoi_emp, polys)
    valid_ids = set(polys['ID_UC_G0'].values)

    emp_sub = voronoi_emp[emp_interior]
    emp_areas = emp_sub['Area'].values
    cv_emp = emp_areas.std() / emp_areas.mean()
    nnd_emp = _pool_nnd(pts_emp, voronoi_emp, valid_ids, emp_interior).mean()
    print(f"Empirical: CV={cv_emp:.4f}, Mean NND={nnd_emp:.0f}m")

    if os.path.exists(NULL_MODEL_PATH):
        print(f"Cache exists: {NULL_MODEL_PATH}")
        return

    rng = np.random.default_rng(42)
    cv_csr, nnd_csr = np.empty(n_sim), np.empty(n_sim)
    cv_ssi, nnd_ssi = np.empty(n_sim), np.empty(n_sim)

    for i in tqdm(range(n_sim), desc="Null model simulations"):
        pts_csr = _random_csr(polys, rng)
        vor_csr = voronoi_partition(pts_csr, polys)
        int_csr = _mark_interior(vor_csr, polys)
        areas = vor_csr[int_csr]['Area'].values
        cv_csr[i] = areas.std() / areas.mean() if len(areas) > 1 else np.nan
        nnd_arr = _pool_nnd(pts_csr, vor_csr, valid_ids, int_csr)
        nnd_csr[i] = nnd_arr.mean() if len(nnd_arr) > 0 else np.nan

        pts_ssi = _random_ssi(polys, rng)
        vor_ssi = voronoi_partition(pts_ssi, polys)
        int_ssi = _mark_interior(vor_ssi, polys)
        areas = vor_ssi[int_ssi]['Area'].values
        cv_ssi[i] = areas.std() / areas.mean() if len(areas) > 1 else np.nan
        nnd_arr = _pool_nnd(pts_ssi, vor_ssi, valid_ids, int_ssi)
        nnd_ssi[i] = nnd_arr.mean() if len(nnd_arr) > 0 else np.nan

    np.savez(NULL_MODEL_PATH,
             cv_poisson=cv_csr, nnd_poisson=nnd_csr,
             cv_ssi=cv_ssi, nnd_ssi=nnd_ssi,
             cv_emp=cv_emp, nnd_emp=nnd_emp)
    print(f"Saved cache to {NULL_MODEL_PATH}")


