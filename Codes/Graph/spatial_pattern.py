    ax_d = fig.add_subplot(sub_gs[0, 0])
    ax_e = fig.add_subplot(sub_gs[1, 0])
    placeholder_ax.axis('off')

    _plot_kde_panel(ax_d, cv_csr, cv_ssi, cv_emp, 'CV of Voronoi cell areas')
    ax_d.set_xlim(0.3, 0.7)
    ax_d.set_ylim(0, 20)
    ax_d.set_xticks([0.3, 0.4, 0.5, 0.6, 0.7])
    ax_d.set_yticks([0, 10, 20])

    _plot_kde_panel(ax_e, nnd_csr, nnd_ssi, nnd_emp, 'Mean NND (km)')
    ax_e.set_xlim(2, 5)
    ax_e.set_ylim(0, 10)
    ax_e.set_xticks([2, 3, 4, 5])
    ax_e.set_yticks([0, 5, 10])


