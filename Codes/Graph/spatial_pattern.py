def generate_voronoi():
    """Generate empirical Voronoi partitions and run null model simulations."""
    polys = gpd.read_file(CLUSTERS_PATH)
    pts_emp = gpd.read_file(CENTERS_PATH)

    center_counts = pts_emp.groupby('ID_UC_G0').size().reset_index(name='Center_Num')
    polys = polys.merge(center_counts, on='ID_UC_G0', how='left')
    polys['Center_Num'] = polys['Center_Num'].fillna(0).astype(int)
    polys = polys[polys['Center_Num'] > 0].copy()

    print("Generating empirical Voronoi partitions...")
    voronoi_emp = voronoi_partition(pts_emp, polys)

    os.makedirs(os.path.dirname(VORONOI_PATH), exist_ok=True)
    voronoi_shp = voronoi_emp.copy()
    voronoi_shp.geometry = voronoi_shp.geometry.apply(
        lambda g: g if isinstance(g, MultiPolygon) else MultiPolygon([g]))
    voronoi_shp.to_file(VORONOI_PATH)
    print(f"Voronoi saved to {VORONOI_PATH}")

    print("Running null model simulations...")
    run_null_model(pts_emp, polys, voronoi_emp)
    print("Done.")


